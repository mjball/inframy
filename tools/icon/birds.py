#!/usr/bin/env python3
"""Generates App/AppIcon.icon/Assets/birds.svg: a flock of tiny birds spelling "86" in the dusk sky.

Each digit is a set of strokes; birds are placed evenly along them with a little jitter, tilt and size variation
so it reads as a flock, not a font. Re-run after tweaking the numbers below, then re-render the icon.
"""
import math
import random
from pathlib import Path

random.seed(86)

CENTER = (512, 392)      # where the "86" sits: the warm sky above the valley between the peaks
DIGIT_H = 104            # digit height in the 1024 canvas
GAP = 22                 # space between the digits
SPACING = 15.5           # distance between birds along a stroke
COLOR = "#1E1742"


def ellipse(cx, cy, rx, ry, t0=0.0, t1=1.0, steps=400):
    return [(cx + rx * math.cos(2 * math.pi * t), cy + ry * math.sin(2 * math.pi * t))
            for t in [t0 + (t1 - t0) * i / steps for i in range(steps + 1)]]


def digit_8(x0, y0, h):
    w = h * 0.56
    top = ellipse(x0 + w / 2, y0 + h * 0.235, w * 0.40, h * 0.235)
    bottom = ellipse(x0 + w / 2, y0 + h * 0.715, w * 0.50, h * 0.285)
    return [top, bottom], w


def digit_6(x0, y0, h):
    w = h * 0.56
    loop = ellipse(x0 + w / 2, y0 + h * 0.70, w * 0.48, h * 0.30)
    # The "hook": starts at the top (a little right of centre) and sweeps LEFT and down into the loop's left side.
    hook = []
    cx, cy = x0 + w * 0.95, y0 + h * 0.70
    rx, ry = w * 0.93, h * 0.70
    for i in range(201):
        ang = math.radians(262 - 82 * i / 200)   # 262° (top) → 180° (left), SVG y-down
        hook.append((cx + rx * math.cos(ang), cy + ry * math.sin(ang)))
    return [hook, loop], w


def sample(path, spacing):
    out, carry = [path[0]], 0.0
    for (ax, ay), (bx, by) in zip(path, path[1:]):
        seg = math.hypot(bx - ax, by - ay)
        while carry + seg >= spacing:
            t = (spacing - carry) / seg
            ax, ay = ax + (bx - ax) * t, ay + (by - ay) * t
            out.append((ax, ay))
            seg = math.hypot(bx - ax, by - ay)
            carry = 0.0
        carry += seg
    return out


def bird(x, y, size, tilt):
    """A distant bird: two shallow arcs meeting at the body ("m" without the middle stroke)."""
    w, h = size, size * 0.42
    return (f'<path transform="translate({x:.1f} {y:.1f}) rotate({tilt:.1f})" '
            f'd="M {-w:.2f} 0 Q {-w / 2:.2f} {-h:.2f} 0 {h * 0.25:.2f} Q {w / 2:.2f} {-h:.2f} {w:.2f} 0"/>')


strokes = []
w8 = DIGIT_H * 0.56
total_w = w8 * 2 + GAP
x0 = CENTER[0] - total_w / 2
y0 = CENTER[1] - DIGIT_H / 2
s8, _ = digit_8(x0, y0, DIGIT_H)
s6, _ = digit_6(x0 + w8 + GAP, y0, DIGIT_H)
strokes = s8 + s6

points = []
for path in strokes:
    for (x, y) in sample(path, SPACING):
        # Skip birds that would overlap one already placed (where strokes meet or cross).
        if all(math.hypot(x - px, y - py) > SPACING * 0.7 for px, py in points):
            points.append((x, y))

birds = []
for (x, y) in points:
    if True:
        jx, jy = random.uniform(-1.6, 1.6), random.uniform(-1.6, 1.6)
        birds.append(bird(x + jx, y + jy, random.uniform(4.6, 6.4), random.uniform(-14, 14)))
# A few strays around the flock, so it reads as birds first.
for (x, y) in [(CENTER[0] - 120, CENTER[1] - 38), (CENTER[0] + 132, CENTER[1] - 58), (CENTER[0] + 104, CENTER[1] + 30)]:
    birds.append(bird(x, y, random.uniform(4.6, 5.6), random.uniform(-10, 10)))

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <!-- Generated by tools/icon/birds.py: a flock spelling "86" (the wink at Samsung). -->
  <g fill="none" stroke="{COLOR}" stroke-width="2.3" stroke-linecap="round" stroke-linejoin="round" opacity="0.88">
    {chr(10).join("    " + b for b in birds).strip()}
  </g>
</svg>
'''
out = Path(__file__).resolve().parents[2] / "App/AppIcon.icon/Assets/birds.svg"
out.write_text(svg)
print(f"{len(birds)} birds → {out}")
